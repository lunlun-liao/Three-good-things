const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
 const context = await browser.newContext({viewport:{width:393,height:851},isMobile:true,hasTouch:true,acceptDownloads:true,timezoneId:'Asia/Taipei'});
 const page = await context.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.BROWSER_BASE_URL || 'http://localhost:8000');
 await page.evaluate(()=>navigator.serviceWorker.ready);
 await page.reload();
 await page.getByRole('button',{name:'＋ 記下一件好事'}).click();
 await page.locator('#entry-date').fill('2026-10-18');
 await page.locator('#entry-text').fill('今天看到漂亮的夕陽 <img src=x onerror=alert(1)>');
 await page.locator('#entry-reflection').fill('因為我願意出門走一走。');
 await page.locator('#entry-category').selectOption('健康／照顧自己');
 await page.getByRole('button',{name:'儲存這份美好'}).click();
 await page.locator('.entry-card').waitFor();
 assert.equal(await page.locator('.entry-card').count(),1);
 assert.equal(await page.locator('.entry-card img').count(),0);
 await page.reload();
 assert.equal(await page.locator('.entry-card').count(),1);
 await page.getByRole('button',{name:/編輯：/}).click();
 await page.locator('#entry-text').fill('今天和家人散步');
 await page.locator('#entry-category').selectOption('家人／朋友');
 await page.getByRole('button',{name:'儲存這份美好'}).click();
 await page.locator('#category-filter').selectOption('工作／學習');
 assert.equal(await page.locator('.entry-card').count(),0);
 await page.locator('#category-filter').selectOption('');
 await page.getByRole('button',{name:'日曆回顧'}).click();
 await page.getByRole('button',{name:'2026-10-18，1 件好事',exact:true}).click();
 assert.equal(await page.locator('.entry-text').textContent(),'今天和家人散步');
 await page.screenshot({path:require('node:path').join(require('node:os').tmpdir(), 'three-good-things-mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
 await page.getByRole('button',{name:'備份與資料'}).click();
 await page.getByText('離線準備完成，下次沒有網路也能開啟與記錄。').waitFor();
 const downloadPromise = page.waitForEvent('download');
 await page.getByRole('button',{name:'↓ 匯出 JSON 備份'}).click();
 const download = await downloadPromise;
 const path = await download.path();
 const backup = JSON.parse(require('node:fs').readFileSync(path,'utf8'));
 assert.equal(backup.entries.length,1);
 const second = await browser.newContext({viewport:{width:1280,height:900}});
 const secondPage = await second.newPage();
 await secondPage.goto(process.env.BROWSER_BASE_URL || 'http://localhost:8000');
 await secondPage.getByRole('button',{name:'備份與資料'}).click();
 secondPage.on('dialog',dialog=>dialog.accept());
 await secondPage.locator('#import-backup').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
 await secondPage.getByText('目前收藏 1 件好事，分布在 1 個日子。').waitFor();
 await secondPage.locator('#import-backup').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
 await secondPage.getByText('已匯入 0 件好事').waitFor();
 await secondPage.locator('#import-backup').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{')});
 await secondPage.getByText('無法讀取 JSON 備份，沒有匯入任何資料。').waitFor();
 assert.equal(await secondPage.locator('#total-count').textContent(),'目前收藏 1 件好事，分布在 1 個日子。');
 await context.setOffline(true);
 await page.reload();
 await page.getByRole('button',{name:'＋ 記下一件好事'}).waitFor();
 await page.locator('#selected-date').fill('2026-10-18');
 assert.equal(await page.locator('.entry-card').count(),1);
 await page.getByRole('button',{name:'＋ 記下一件好事'}).click();
 await page.locator('#entry-text').fill('離線也能記錄');
 await page.getByRole('button',{name:'儲存這份美好'}).click();
 assert.equal(await page.locator('.entry-card').count(),2);
 page.on('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'刪除：離線也能記錄'}).click();
 assert.equal(await page.locator('.entry-card').count(),1);
 await page.reload();
 await page.locator('#selected-date').fill('2026-10-18');
 assert.equal(await page.locator('.entry-card').count(),1);
 assert.deepEqual(errors,[]);
 await context.setOffline(false);
 const broken = await browser.newContext();
 await broken.addInitScript(()=>localStorage.setItem('three-good-things:v1','broken'));
 const brokenPage = await broken.newPage();
 await brokenPage.goto(process.env.BROWSER_BASE_URL || 'http://localhost:8000');
 assert.equal(await brokenPage.locator('#storage-warning').isVisible(),true);
 assert.equal(await brokenPage.locator('#add-entry').isDisabled(),true);
 assert.equal(await brokenPage.evaluate(()=>localStorage.getItem('three-good-things:v1')),'broken');
 console.log('PASS: mobile CRUD, persistence, safe text rendering, category filter, calendar, JSON export/import, duplicate/malformed import, offline reload/write/delete, corrupt storage protection, desktop import, no page errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
